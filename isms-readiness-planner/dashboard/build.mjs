import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.dirname(here);
const read=p=>fs.existsSync(path.join(root,p))?fs.readFileSync(path.join(root,p),'utf8').replace(/^\uFEFF/,''):'';
const json=p=>{try{return JSON.parse(read(p));}catch{return null;}};
const lines=p=>read(p).split(/\r?\n/).filter(Boolean).flatMap(s=>{try{return [JSON.parse(s)];}catch{return [];}});
const queueDir=path.join(root,'queue');
const queue=fs.existsSync(queueDir)?fs.readdirSync(queueDir).filter(p=>p.endsWith('.md')).sort().reverse().slice(0,10).map(p=>({path:'queue/'+p,text:read('queue/'+p)})):[];
const board=json('board/board.json');
const inbox=lines('board/inbox.jsonl');
const data={context:read('PHISHGUARD-CONTEXT.md'),strategy:Object.fromEntries(['offer','icp','positioning','voice','utm-taxonomy','proof-inventory'].map(n=>[n,read('strategy/'+n+'.md')])),brief:read('brief-latest.md'),queue,cards:board?.cards??inbox.map((x,i)=>({...x.card,id:'pending-'+(i+1)})),boardPending:!board,runs:lines('runlog.jsonl').slice(-12),digest:read('gtm-latest.md'),progress:fs.existsSync(path.join(root,'progress'))?fs.readdirSync(path.join(root,'progress'),{recursive:true}).filter(p=>String(p).endsWith('.json')).map(p=>json('progress/'+String(p).replaceAll('\\','/'))).filter(Boolean):[]};
const payload=JSON.stringify(data).replaceAll('<','\\u003c');
let shell=read('dashboard/src/index.html');
const css=read('dashboard/src/app.css');
const pages=fs.readdirSync(path.join(here,'src/pages')).filter(p=>p.endsWith('.html')).sort().map(p=>read('dashboard/src/pages/'+p)).join('\n');
shell=shell.replace('<!-- CSS -->',()=>'<style>'+css+'</style>').replace('<!-- PAGES -->',()=>pages).replace('<!-- JS -->',()=>'<script id="data" type="application/json">'+payload+'</script><script>'+read('dashboard/src/app.js')+'</script>');
if(/<!-- (CSS|PAGES|JS) -->/.test(shell))throw Error('Build placeholders remain');
if(/(?:https?:\/\/)?(?:[A-Z]:\\|\/Users\/)/.test(shell))throw Error('Absolute machine path found');
const tmp=path.join(here,'index.html.tmp');
fs.writeFileSync(tmp,shell,'utf8');
fs.renameSync(tmp,path.join(here,'index.html'));
console.log('Built dashboard/index.html from current local sources');
